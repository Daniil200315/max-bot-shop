function cheesePortions(name, pricePerKg, portionPrices, sortOrderStart, imageUrl, info) {
  const weights = ['~200 г', '~300 г', '~500 г'];
  return portionPrices.map((price, i) => ({
    name,
    category: 'Сыры',
    price_kopecks: rub(price),
    unit: 'порция',
    weight_label: weights[i],
    image_url: imageUrl,
    sort_order: sortOrderStart + i,
    description: `${info.description} · ${pricePerKg.toLocaleString('ru-RU')} ₽/кг`,
    nutrition_info: info.nutrition_info,
    ingredients: info.ingredients,
  }));
}
